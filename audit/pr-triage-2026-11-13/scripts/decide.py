def classify_log(path):
    """Cuenta en un registro TAP los fallos de aserción y los cortes por tiempo."""
    if not os.path.exists(path): return 0, 0
    txt = open(path, encoding='utf-8', errors='replace').read()
    blocks = re.split(r'\n(?=(?:not )?ok \d+ )', txt)
    asserts = sum(1 for b in blocks if b.startswith('not ok') and 'AssertionError' in b)
    tmo = sum(1 for b in blocks if b.startswith('not ok') and 'AssertionError' not in b and re.search(r'timed out|TimeoutError|Timeout \d+ms', b))
    return asserts, tmo
