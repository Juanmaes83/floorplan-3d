#!/usr/bin/env node
// SCULPT-R02-A · verbatim extracts from the donor snapshot (zhuzhuyumeng/floorplan-3d @324eb64).
// --verify SNAPSHOT_DIR  (default) checks that every extract in workshop/ is byte-identical to its donor line range.
// --write  SNAPSHOT_DIR  regenerates workshop/donor-ceiling-extracts.js and workshop/donor-rules-reference.txt.
// Reads files only; never writes outside workshop/; runs no donor code.
'use strict';
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const HERE=__dirname,WS=path.join(HERE,'workshop');
const sha=s=>crypto.createHash('sha256').update(s,'utf8').digest('hex');
// [id, donor file, first line, last line, role]
const EXTRACTS=[
 ['A','js/project-model.js',185,226,'executable: footprint, overlap (inherited from 88323f3) + furniturePlacement, resolveFurniturePlacement (new in 324eb64)'],
 ['B','index.html',541,545,'executable data: CEILING_LIB (6 ceiling / high items: type, name, width, depth, colour, height mm)'],
 ['C','js/project-model.js',114,114,'reference: per-item bounds for layer, ceilingDrop, curtainLength'],
 ['D','js/project-model.js',168,168,'reference: drop + h + curtain <= height - floorFinish'],
 ['E','index.html',1668,1668,'reference: defaults on creation (acwall drop 200, curtain length = clear - h - 20)'],
 ['F','index.html',3173,3185,'reference: 3D vertical placement (top = H - drop, bottom = top - h, curtain below the track)'],
 ['G','tests/model.test.cjs',84,94,'test: the donor unit test added by 324eb64, run unchanged against extract A']
];
const slice=(dir,f,a,b)=>fs.readFileSync(path.join(dir,f),'utf8').split('\n').slice(a-1,b).join('\n');
function build(dir){
 const get=id=>{const e=EXTRACTS.find(x=>x[0]===id);return {e,text:slice(dir,e[1],e[2],e[3])};};
 const block=id=>{const {e,text}=get(id);return `// ---- BEGIN EXTRACT ${id} · ${e[1]}:${e[2]}-${e[3]} @324eb64 · sha256 ${sha(text)}\n${text}\n// ---- END EXTRACT ${id}`;};
 const js=`/* SCULPT-R02-A workshop · VERBATIM extracts from zhuzhuyumeng/floorplan-3d @324eb64cf9b26f6d4df8323c2dec4591fa4691e3
 * (PR wy51ai/floorplan-3d#17, author olifod). MIT, (c) 2026 wuyi: see LICENSE-donor-MIT.txt. GOV-05: legal review pending.
 * Generated by extract-donor.cjs --write; do not edit by hand. The lines between BEGIN/END are byte-identical to the donor.
 * Units: mm. Plan axes: x right, y down. f.rot in degrees (positive = clockwise on screen with y down).
 * Walls: donor format [x0, y0, x1, y1, kind, id] (axis-aligned rectangles). */
(function (root) {
  'use strict';
${block('A')}
${block('B')}
  const api = { footprint, overlap, furniturePlacement, resolveFurniturePlacement, CEILING_LIB };
  if (typeof module === 'object' && module.exports) module.exports = api; else root.RubikR02DonorExtracts = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
 const testJs=`// SCULPT-R02-A workshop baseline: the donor's own unit test from 324eb64, unchanged, run against the verbatim extracts.
// Generated by extract-donor.cjs --write. M is the workshop module instead of the donor's js/project-model.js.
const {test}=require('node:test');const assert=require('node:assert/strict');const M=require('./donor-ceiling-extracts.js');
${block('G')}
`;
 const ref=EXTRACTS.filter(e=>e[4].startsWith('reference')).map(e=>{const t=slice(dir,e[1],e[2],e[3]);return `==== EXTRACT ${e[0]} · ${e[1]}:${e[2]}-${e[3]} @324eb64 · sha256 ${sha(t)} · ${e[4]}\n${t}\n==== END ${e[0]}`;}).join('\n\n')+'\n';
 return {js,ref,testJs};
}
function extractsIn(text){
 const out={};const re=/(?:\/\/ ----|====) BEGIN EXTRACT ([A-Z]) · .*? · sha256 ([0-9a-f]{64})[^\n]*\n([\s\S]*?)\n(?:\/\/ ---- END EXTRACT|==== END) \1/g;
 let m;while((m=re.exec(text)))out[m[1]]={sha:m[2],text:m[3]};
 return out;
}
function verifyWorkshop(dir){
 const all={...extractsIn(fs.readFileSync(path.join(WS,'donor-ceiling-extracts.js'),'utf8')),...extractsIn(fs.readFileSync(path.join(WS,'donor-placement.test.cjs'),'utf8')),...extractsIn(fs.readFileSync(path.join(WS,'donor-rules-reference.txt'),'utf8').replace(/==== EXTRACT/g,'==== BEGIN EXTRACT'))};
 const problems=[];
 for(const [id,f,a,b] of EXTRACTS){
  const w=all[id];if(!w){problems.push(id+': missing in workshop');continue;}
  if(sha(w.text)!==w.sha)problems.push(id+': text does not match its recorded hash');
  if(dir){const d=slice(dir,f,a,b);if(d!==w.text)problems.push(id+`: differs from donor ${f}:${a}-${b}`);}
 }
 return problems;
}
if(require.main===module){
 const [mode,dir]=process.argv[2]?.startsWith('--')?[process.argv[2],process.argv[3]]:['--verify',process.argv[2]];
 if(mode==='--write'){if(!dir)throw Error('--write needs the snapshot directory');const {js,ref,testJs}=build(dir);fs.writeFileSync(path.join(WS,'donor-ceiling-extracts.js'),js);fs.writeFileSync(path.join(WS,'donor-placement.test.cjs'),testJs);fs.writeFileSync(path.join(WS,'donor-rules-reference.txt'),ref);console.log('workshop extracts written');}
 else{const p=verifyWorkshop(dir||null);if(p.length){console.error(p.join('\n'));process.exit(5);}console.log(`extracts verified${dir?' against '+dir:' (self-consistency only)'}`);}
}
module.exports={EXTRACTS,extractsIn,verifyWorkshop};
